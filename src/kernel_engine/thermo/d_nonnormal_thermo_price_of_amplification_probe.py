# ============================================================ core linear-OU thermodynamics
def lyap_sigma(A, D):
    return solve_lyapunov(A, -2.0 * D)                       # A S + S A^T = -2 D

def ep_rate(A, Sigma, D):
    """steady-state entropy-production rate = Tr[Omega^T D^-1 Omega Sigma], Omega = A + D Sigma^-1 (local mean vel)."""
    Si = np.linalg.inv(Sigma); Di = np.linalg.inv(D)
    Om = A + D @ Si
    return float(np.trace(Om.T @ Di @ Om @ Sigma))

def ep_rate_Q(A, Sigma, D):
    """independent closed form via the antisymmetric probability-current matrix Q = A Sigma + D (Q=0 <=> equilibrium)."""
    Q = A @ Sigma + D
    Si = np.linalg.inv(Sigma); Di = np.linalg.inv(D)
    return float(np.trace(Di @ Q @ Si @ Q.T)), Q

def pseudo_sigmin(A, ngrid=2001):
    """pseudospectral distance-to-instability = min_w sigma_min(i w I - A)  (Trefethen-Embree)."""
    n = A.shape[0]; ev = np.linalg.eigvals(A)
    wmax = 2.0 * (1.0 + float(np.max(np.abs(ev.imag))))
    ws = np.linspace(-wmax, wmax, ngrid); I = np.eye(n)
    best = np.inf
    for w in ws:
        s = svdvals(1j * w * I - A)[-1]
        if s < best: best = s
    return float(best)

def kreiss_const(A, ne=140, no=161):
    """Kreiss constant K = sup_{Re z>0} Re(z) ||(z I - A)^-1||  (the transient/tier-3 governor). K>=1 always;
       a fine geometric grid near the spectrum is needed (else K undershoots 1)."""
    n = A.shape[0]; ev = np.linalg.eigvals(A)
    emax = 2.0 * (1.0 + float(np.max(np.abs(ev.real)))); wmax = 2.0 * (1.0 + float(np.max(np.abs(ev.imag))))
    etas = np.concatenate([np.geomspace(1e-3, 0.2, ne // 2), np.linspace(0.2, emax, ne - ne // 2)])
    oms = np.linspace(-wmax, wmax, no); I = np.eye(n); K = 0.0
    for e in etas:
        for w in oms:
            K = max(K, e * np.linalg.norm(np.linalg.inv((e + 1j * w) * I - A), 2))
    return float(K)

def transient_gmax(A, nt=400, tmax=None):
    """actual transient growth G_max = sup_{t>=0} ||e^{At}||_2 (the tier-3 transient the abscissa/Kreiss bound)."""
    ev = np.linalg.eigvals(A); tmax = tmax if tmax else 8.0 / max(-np.max(ev.real), 1e-3)
    return float(max(np.linalg.norm(expm(A * t), 2) for t in np.linspace(0.0, tmax, nt)))

def sim_ep_sekimoto(A, D, rng, dt=1e-3, nsteps=80000, n=4000, burn=15000):
    """INDEPENDENT Ep: direct overdamped-Langevin sim, Sekimoto heat rate dQ = f o dx (Stratonovich), f = A x.
       Steady-state <dQ>/dt = entropy-production rate. Uses NO Sigma -> breaks the 'both from Sigma' tautology."""
    nn = A.shape[0]; L = np.linalg.cholesky(2.0 * D); sq = math.sqrt(dt)
    x = rng.standard_normal((n, nn)); acc = 0.0; cnt = 0
    for k in range(nsteps):
        f0 = x @ A.T
        dxi = f0 * dt + (rng.standard_normal((n, nn)) @ L.T) * sq
        xnew = x + dxi
        f1 = xnew @ A.T
        dQ = np.sum(0.5 * (f0 + f1) * dxi, axis=1)           # Stratonovich midpoint force . displacement
        if k >= burn: acc += dQ.mean(); cnt += 1
        x = xnew
    return acc / cnt / dt

def make_A(lam, Nmat, g):
    V = np.eye(len(lam)) + g * Nmat
    return V @ np.diag(lam) @ np.linalg.inv(V)               # eigenvalues EXACTLY lam; non-normality grows with g

def normal_ref_var(lam):
    """Var of the NORMAL operator with the same (real) spectrum = symmetric A = equilibrium floor: sum 1/|lam_i|."""
    return float(np.sum(1.0 / np.abs(np.real(lam))))

def slope(x, y):
    x = np.asarray(x, float); y = np.asarray(y, float)
    return float(np.polyfit(np.log(x), np.log(y), 1)[0])


