# ============================================================ Harada-Sasa structural anchor (FDT violation ~ Q)
def harada_sasa_structure(rng):
    """external anchor: dissipation = integrated FDT-violation (Harada-Sasa 2005). For OU: response chi(t)=e^{At},
       correlation C(t)=e^{At}Sigma; FDT-violation V(t)=d/dt C(t) + chi(t) = e^{At}(A Sigma + I) = e^{At} Q.
       => V==0 (FDT holds) IFF Q==0 IFF symmetric/equilibrium; V!=0 (FDT broken) driven by the SAME Q that gives Ep.
       Verified numerically at t=0: V(0)=Q, and Ep=Tr[Q Sigma^-1 Q^T]. Ties fluctuation-amp and dissipation to ONE Q."""
    lam = np.array([-1.0, -1.7, -2.3]); Nmat = np.triu(rng.standard_normal((3, 3)), 1); out = []
    for tag, g in [("symmetric", 0.0), ("nonnormal", 1.8)]:
        A = make_A(lam, Nmat, g); S = lyap_sigma(A, np.eye(3)); Q = A @ S + np.eye(3)
        ts = np.linspace(0, 2.0, 25)
        Vnorm = float(np.trapezoid([np.linalg.norm(expm(A * t) @ Q) for t in ts], ts))   # integrated FDT-violation
        ep, _ = ep_rate_Q(A, S, np.eye(3))
        out.append(dict(case=tag, g=g, Q_norm=float(np.linalg.norm(Q)),
                        fdt_holds=bool(np.linalg.norm(Q) < 1e-9), fdt_violation_integral=Vnorm, ep=ep))
    return out


