    kreiss_mis = float(np.median(np.abs(p_eps - p_Ks))) if n else None
    # Pearson r between the (wandering) Ep and dVar exponents = the 'same governor' signature (r~1 but not identical)
    r_ep_dv = float(np.corrcoef(p_eps, p_dvs)[0, 1]) if n > 2 else None
